"""Antibody Writer: turns one failure into a GENERAL executable check for its bug class,
plus a short fix recipe. Counterexample-guided (CEGIS): the check is evaluated on bug
variants (must be flagged) and benign look-alikes (must pass); misses and false alarms are
fed back for up to CEGIS_MAX_ROUNDS refinements. Variants/look-alikes are generated by a
separate call that never sees the check, and are confirmed by the hidden reference suite.
"""
from __future__ import annotations

import json
from concurrent.futures import ThreadPoolExecutor

import config
import db
import gate
import llm
import sandbox
import signature
import workers

WRITER_SYSTEM = """You are the Antibody Writer. A coding agent shipped a regression in a Python
billing service. Write ONE executable check that would have caught it and that also catches the
whole BUG CLASS in this area, not just this one instance, without flagging correct code.

Rules for check_code:
- A pytest module. It may use: pytest, hypothesis, decimal, datetime, zoneinfo, math,
  collections, itertools, inspect, ast, and `from antibody_rt import source_of, ast_of`
  (returns a module's source / AST for static rules). Import the code under test from `billing.*`.
- FORBIDDEN: os, subprocess, socket, shutil, requests, pathlib, importlib, open(), eval/exec,
  getattr/setattr, dunder attributes. It runs in a sandbox with a 10 s limit.
- Test behaviour through the public functions, via properties/invariants that hold for every
  correct implementation (e.g. "results are newest-first with ties broken by id", "money values are
  Decimal with 2 places", "dates are the customer's local date"). Prefer several focused test
  functions over one. Do NOT copy one specific expected number from the trace.
- It must PASS on the current (correct) code shown in the context, and FAIL on the buggy change.
fix_recipe: 2-4 imperative sentences a developer/agent can apply to fix this class of bug.
signature.apis: the public functions/types involved (e.g. "billing.reports.invoice_page")."""

CHECK_SCHEMA = {
    "type": "object",
    "properties": {
        "bug_class": {"type": "string", "enum": workers.BUG_CLASSES},
        "title": {"type": "string"},
        "check_kind": {"type": "string", "enum": ["pytest", "hypothesis", "ast"]},
        "check_code": {"type": "string"},
        "fix_recipe": {"type": "string"},
        "apis": {"type": "array", "items": {"type": "string"}},
    },
    "required": ["bug_class", "title", "check_kind", "check_code", "fix_recipe", "apis"],
    "additionalProperties": False,
}

MATERIAL_SYSTEM = """You generate test material for a bug-detector. Given a regression and its bug
class, write (1) VARIANTS: other realistic buggy re-implementations of functions in the shown files
that exhibit the SAME bug class in different ways, and (2) LOOKALIKES: correct re-implementations
that look superficially similar (refactors, renamed variables, different but equivalent logic) and
must NOT be flagged. Each item is a complete module-level function with its original signature.
No comments revealing intent."""

FN = {"type": "object",
      "properties": {"file": {"type": "string"}, "function": {"type": "string"},
                     "function_source": {"type": "string"}},
      "required": ["file", "function", "function_source"], "additionalProperties": False}
MATERIAL_SCHEMA = {"type": "object",
                   "properties": {"variants": {"type": "array", "items": FN},
                                  "lookalikes": {"type": "array", "items": FN}},
                   "required": ["variants", "lookalikes"], "additionalProperties": False}


def _files_from(items, allowed):
    out = []
    for v in items:
        if v["file"] not in allowed:
            continue
        try:
            base = (config.BILLING_REPO / v["file"]).read_text()
            out.append({v["file"]: workers.splice(base, v["function"], v["function_source"], [])})
        except Exception:
            continue
    return out


def cegis_material(change: dict, bug_class: str, run_id=None) -> tuple[list, list]:
    """Writer-side variants (8) and look-alikes (20), confirmed by the reference suite."""
    area = gate.AREA[change["worker"]]
    src = "\n".join(f"### FILE: {f}\n```python\n{(config.BILLING_REPO / f).read_text()}```" for f in area)
    r = llm.call("adapter", MATERIAL_SYSTEM,
                 f"Bug class: {bug_class}\nRegression diff:\n{change['diff']}\n\n"
                 f"Write {config.GATE_N_VARIANTS + 3} VARIANTS and {config.GATE_N_GOOD + 4} LOOKALIKES.",
                 context=src, schema=MATERIAL_SCHEMA, run_id=run_id)
    vs = _files_from(r["data"]["variants"], area)
    ls = _files_from(r["data"]["lookalikes"], area)
    with ThreadPoolExecutor(6) as ex:
        vl = list(ex.map(lambda f: workers.reference_label(f)["label"], vs))
        ll = list(ex.map(lambda f: workers.reference_label(f)["label"], ls))
    variants = [f for f, l in zip(vs, vl) if l == "buggy"][: config.GATE_N_VARIANTS]
    lookalikes = [f for f, l in zip(ls, ll) if l == "good"][: config.GATE_N_GOOD]
    return variants, lookalikes


def _fn_of(files: dict) -> str:
    rel, txt = next(iter(files.items()))
    return f"# {rel}\n" + txt


def write_check(change_id: int, run_id: str | None = None, log=print, max_rounds: int | None = None) -> dict:
    """Full Writer pipeline for one buggy change. Returns the stored check row + evidence."""
    ch = db.query("SELECT * FROM changes WHERE id=?", change_id)[0]
    ch["files"] = json.loads(ch["files"])
    ch["failed_tests"] = json.loads(ch["failed_tests"] or "[]")
    issue = next(i for i in workers.load_issues(ch["worker"]) if i["id"] == ch["issue_id"])
    context = workers.package_source(strip=False)  # long context: the whole package, cached

    base_prompt = (f"Worker {ch['worker']} ticket {issue['id']}: {issue['title']}\n{issue['body']}\n\n"
                   f"Regression diff:\n{ch['diff']}\n\nFailing CI output:\n{ch['failing_trace']}\n"
                   f"Failing test names: {ch['failed_tests']}")
    log(f"[writer] change {change_id} ({ch['worker']} {ch['issue_id']}, class={ch['bug_class']}): drafting check…")
    with ThreadPoolExecutor(2) as ex:
        f_check = ex.submit(llm.call, "writer", WRITER_SYSTEM, base_prompt, context=context,
                            schema=CHECK_SCHEMA, run_id=run_id)
        f_mat = ex.submit(cegis_material, ch, ch["bug_class"] or "other", run_id)
        draft = f_check.result()["data"]
        variants, lookalikes = f_mat.result()
    log(f"[writer] CEGIS material confirmed by reference suite: {len(variants)} variants, {len(lookalikes)} look-alikes")

    code, history = draft["check_code"], []
    max_rounds = max_rounds or config.CEGIS_MAX_ROUNDS
    for rnd in range(1, max_rounds + 1):
        res = gate.run_many(code, [ch["files"], {}] + variants + lookalikes)
        orig_flag, fixed_pass = res[0].flagged, res[1].status == "pass"
        v_res, l_res = res[2:2 + len(variants)], res[2 + len(variants):]
        missed = [variants[i] for i, r in enumerate(v_res) if not r.flagged]
        false_alarms = [(lookalikes[i], l_res[i]) for i, r in enumerate(l_res) if r.status != "pass"]
        static_ok, why = sandbox.static_screen(code)
        h = {"round": rnd, "catches_original": orig_flag, "passes_fixed": fixed_pass,
             "variants_caught": len(variants) - len(missed), "variants_total": len(variants),
             "lookalikes_flagged": len(false_alarms), "lookalikes_total": len(lookalikes),
             "static": why}
        history.append(h)
        log(f"[cegis r{rnd}] original {'CAUGHT' if orig_flag else 'missed'} | fixed {'pass' if fixed_pass else 'FAIL'} | "
            f"variants {h['variants_caught']}/{h['variants_total']} | look-alikes flagged {h['lookalikes_flagged']}/{h['lookalikes_total']}")
        done = (static_ok and orig_flag and fixed_pass and not missed and not false_alarms)
        if done or rnd == max_rounds:
            break
        feedback = []
        if not static_ok:
            feedback.append(f"Static screen rejected the check: {why}")
        if not orig_flag:
            feedback.append(f"It does NOT fail on the original buggy change (status {res[0].status}). Output:\n{res[0].output[-1200:]}")
        if not fixed_pass:
            feedback.append(f"It FAILS on the correct code. Output:\n{res[1].output[-1500:]}")
        for m in missed[:3]:
            feedback.append(f"MISSED this buggy variant (must fail):\n{_fn_of(m)[-2500:]}")
        for la, r in false_alarms[:3]:
            feedback.append(f"FALSELY FLAGGED this correct look-alike (must pass). Output:\n{r.output[-800:]}\nCode:\n{_fn_of(la)[-2000:]}")
        r = llm.call("writer", WRITER_SYSTEM,
                     base_prompt + f"\n\nYour current check:\n```python\n{code}\n```\n\nCounterexamples:\n"
                     + "\n\n".join(feedback) + "\n\nReturn an improved check (same JSON shape).",
                     context=context, schema=CHECK_SCHEMA, run_id=run_id)
        draft = r["data"]
        code = draft["check_code"]

    sig = signature.build(ch["failing_trace"], ch["failed_tests"], draft["apis"], draft["bug_class"])
    evidence = {"origin_change": change_id, "issue": ch["issue_id"], "cegis": history}
    h = sandbox.code_hash(code)
    existing = db.query("SELECT id FROM checks WHERE hash=?", h)
    if existing:
        check_id = existing[0]["id"]
    else:
        check_id = db.insert("checks", hash=h, origin_worker=ch["worker"], owner_worker=ch["worker"],
                             bug_class=draft["bug_class"], signature=sig, kind=draft["check_kind"],
                             code=code, fix_recipe=draft["fix_recipe"], cegis_rounds=len(history),
                             evidence=evidence, parent_id=None)
    log(f"[writer] stored check #{check_id} '{draft['title']}' ({draft['check_kind']}, {len(history)} CEGIS round(s))")
    return {"check_id": check_id, "title": draft["title"], "code": code, "fix_recipe": draft["fix_recipe"],
            "bug_class": draft["bug_class"], "signature": sig, "cegis": history,
            "original": {"buggy": ch["files"]}}


if __name__ == "__main__":
    import sys
    cid = int(sys.argv[1])
    out = write_check(cid, run_id="writer-dev")
    print(out["code"])
    print("RECIPE:", out["fix_recipe"])
    v = gate.evaluate(out["check_id"], db.query("SELECT worker FROM changes WHERE id=?", cid)[0]["worker"],
                      original=out["original"], run_id="writer-dev")
    print(json.dumps(v, indent=1))
